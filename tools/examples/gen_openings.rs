use std::collections::BTreeMap;
use std::fs;

use othello::board::{Board, legal_moves, play, squares};
use othello_tools::sym::canonical;

const PER_SET: usize = 512;
const PLIES: usize = 8;

type Groups = BTreeMap<(u64, u64), Vec<Vec<u8>>>;

fn collect(board: Board, seq: &mut Vec<u8>, key: Option<(u64, u64)>, groups: &mut Groups) {
    if seq.len() == PLIES {
        if let Some(key) = key {
            let group = groups.entry(key).or_default();
            if group.len() < PER_SET {
                group.push(seq.clone());
            }
        }
        return;
    }
    for square in squares(legal_moves(board.me, board.opp)) {
        seq.push(square);
        let child = play(board, square);
        let key = if seq.len() == 4 {
            Some(canonical(child))
        } else {
            key
        };
        collect(child, seq, key, groups);
        seq.pop();
    }
}

fn name(square: u8) -> String {
    let file = (b'a' + square % 8) as char;
    let rank = (b'1' + square / 8) as char;
    format!("{file}{rank}")
}

fn main() {
    let mut groups = Groups::new();
    collect(Board::START, &mut Vec::new(), None, &mut groups);
    let groups: Vec<Vec<Vec<u8>>> = groups.into_values().collect();
    let mut sets = [Vec::new(), Vec::new(), Vec::new()];
    let mut group = 0;
    for set in &mut sets {
        while set.len() < PER_SET {
            let openings = &groups[group];
            group += 1;
            for seq in openings {
                if set.len() == PER_SET {
                    break;
                }
                set.push(
                    seq.iter()
                        .map(|&square| name(square))
                        .collect::<Vec<_>>()
                        .join(" "),
                );
            }
        }
    }
    let base = concat!(env!("CARGO_MANIFEST_DIR"), "/../bench");
    let files = [
        "openings_tune.txt",
        "openings_validation.txt",
        "openings_final.txt",
    ];
    for (file, set) in files.iter().zip(sets) {
        let mut text = String::from(
            "# generated by tools/examples/gen_openings.rs: 8-ply openings, groups assigned whole by canonical D4 key order\n",
        );
        text.push_str(&set.join("\n"));
        text.push('\n');
        fs::write(format!("{base}/{file}"), text).unwrap();
    }
}
