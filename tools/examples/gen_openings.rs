use std::collections::{BTreeMap, BTreeSet};
use std::fs;

use othello::board::{Board, legal_moves, play, squares};
use othello_tools::sym::canonical;

const PER_SET: usize = 512;
const NEW_SET: usize = 1024;
const NEW_CAP: usize = 8192;
const PLIES: usize = 8;

type Groups = BTreeMap<(u64, u64), Vec<Vec<u8>>>;

fn collect(
    board: Board,
    seq: &mut Vec<u8>,
    key: Option<(u64, u64)>,
    groups: &mut Groups,
    cap: usize,
) {
    if seq.len() == PLIES {
        if let Some(key) = key {
            let group = groups.entry(key).or_default();
            if group.len() < cap {
                group.push(seq.clone());
            }
        }
        return;
    }
    for square in squares(legal_moves(board.me, board.opp)) {
        seq.push(square);
        let child = play(board, square);
        let key = if seq.len() == 4 {
            Some(canonical(child))
        } else {
            key
        };
        collect(child, seq, key, groups, cap);
        seq.pop();
    }
}

fn name(square: u8) -> String {
    let file = (b'a' + square % 8) as char;
    let rank = (b'1' + square / 8) as char;
    format!("{file}{rank}")
}

fn parse_square(text: &str) -> u8 {
    let bytes = text.as_bytes();
    (bytes[1] - b'1') * 8 + (bytes[0] - b'a')
}

fn end_key(line: &str) -> (u64, u64) {
    let mut board = Board::START;
    for text in line.split_whitespace() {
        board = play(board, parse_square(text));
    }
    canonical(board)
}

fn main() {
    let mut groups = Groups::new();
    collect(Board::START, &mut Vec::new(), None, &mut groups, PER_SET);
    let mut new_groups = Groups::new();
    collect(
        Board::START,
        &mut Vec::new(),
        None,
        &mut new_groups,
        NEW_CAP,
    );
    let groups: Vec<Vec<Vec<u8>>> = groups.into_values().collect();
    let mut buckets: [Vec<&Vec<Vec<u8>>>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    for (index, group) in groups.iter().enumerate() {
        buckets[index % 3].push(group);
    }
    let mut sets: [Vec<String>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    for (set_index, bucket) in buckets.iter().enumerate() {
        let count = bucket.len();
        let base = (PER_SET / count).max(1);
        let mut group_lines: Vec<Vec<String>> = Vec::with_capacity(count);
        for (index, group) in bucket.iter().enumerate() {
            let extra = usize::from(index < PER_SET % count);
            let take = (base + extra).min(group.len());
            let stride = (group.len() / take).max(1);
            let lines = (0..take)
                .map(|step| {
                    let opening = &group[(step * stride).min(group.len() - 1)];
                    opening
                        .iter()
                        .map(|&square| name(square))
                        .collect::<Vec<_>>()
                        .join(" ")
                })
                .collect();
            group_lines.push(lines);
        }
        let longest = group_lines.iter().map(Vec::len).max().unwrap_or(0);
        for step in 0..longest {
            for lines in &group_lines {
                if let Some(line) = lines.get(step) {
                    sets[set_index].push(line.clone());
                    if sets[set_index].len() == PER_SET {
                        break;
                    }
                }
            }
            if sets[set_index].len() == PER_SET {
                break;
            }
        }
    }
    let base = concat!(env!("CARGO_MANIFEST_DIR"), "/../bench");
    let existing = [
        "openings_tune.txt",
        "openings_validation.txt",
        "openings_final.txt",
    ];
    let mut used = BTreeSet::new();
    for file in existing {
        let text = fs::read_to_string(format!("{base}/{file}")).unwrap();
        for line in text.lines().filter(|line| !line.starts_with('#')) {
            used.insert(end_key(line));
        }
    }
    let mut seen = BTreeSet::new();
    let mut fresh = Vec::new();
    let groups: Vec<Vec<Vec<u8>>> = new_groups.into_values().collect();
    let longest = groups.iter().map(Vec::len).max().unwrap_or(0);
    for step in 0..longest {
        for group in &groups {
            if let Some(opening) = group.get(step) {
                let line = opening
                    .iter()
                    .map(|&square| name(square))
                    .collect::<Vec<_>>()
                    .join(" ");
                let key = end_key(&line);
                if !used.contains(&key) && seen.insert(key) {
                    fresh.push(line);
                    if fresh.len() == NEW_SET {
                        break;
                    }
                }
            }
        }
        if fresh.len() == NEW_SET {
            break;
        }
    }
    assert_eq!(fresh.len(), NEW_SET, "not enough fresh openings");
    let mut text = String::from(
        "# generated by tools/examples/gen_openings.rs: 1,024 fresh 8-ply openings, canonical end positions disjoint from the three frozen sets\n",
    );
    text.push_str(&fresh.join("\n"));
    text.push('\n');
    fs::write(format!("{base}/openings_probcut2.txt"), text).unwrap();

    let base = concat!(env!("CARGO_MANIFEST_DIR"), "/../bench");
    let files = [
        "openings_tune.txt",
        "openings_validation.txt",
        "openings_final.txt",
    ];
    for (file, set) in files.iter().zip(sets) {
        let mut text = String::from(
            "# generated by tools/examples/gen_openings.rs: 8-ply openings, groups assigned whole, round-robin by canonical D4 key, lines interleaved across groups\n",
        );
        text.push_str(&set.join("\n"));
        text.push('\n');
        fs::write(format!("{base}/{file}"), text).unwrap();
    }
}
